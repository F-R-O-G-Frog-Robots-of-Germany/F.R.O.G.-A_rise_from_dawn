package org.firstinspires.ftc.teamcode.limelight;

import org.firstinspires.ftc.robotcore.external.navigation.AngleUnit;
import org.firstinspires.ftc.robotcore.external.navigation.DistanceUnit;
import org.firstinspires.ftc.robotcore.external.navigation.Pose3D;
import org.firstinspires.ftc.robotcore.external.navigation.Position;
import org.firstinspires.ftc.robotcore.external.navigation.YawPitchRollAngles;

/** Verifies the SDK optical-frame boundary independently of the hinge solver. */
public final class HiveLimelightObservationChecks {
    private static int checks;

    public static void main(String[] args) {
        identity_and_units();
        independent_axis_rotations();
        official_inverse_pose_example();
        complete_pose_example();
        invalid_observations();
        System.out.println("Hive Limelight observation checks passed: " + checks);
    }

    private static void identity_and_units() {
        HivePoseEstimator.Observation observation = HiveLimelightObservation.from_target_pose(
                30, pose(DistanceUnit.METER, .254, -.508, 1.016, 0, 0, 0), 1234, true);
        check(observation.tagId == 30 && observation.captureTimeMs == 1234
                && observation.timingAssumed, "ID and caller timing provenance preserved");
        vector(new double[]{40, -10, 20}, observation.translation_camera_tag(), "metres to FLU inches");
        vector(new double[]{0, 0, 1, -1, 0, 0, 0, -1, 0},
                observation.rotation_camera_tag(), "camera basis changes, tag basis does not");
        HivePoseEstimator.Observation inches = HiveLimelightObservation.from_target_pose(
                31, pose(DistanceUnit.INCH, 2, 3, 4, 0, 0, 0), 10);
        vector(new double[]{4, -2, -3}, inches.translation_camera_tag(), "inch input remains inches");
        check(!inches.timingAssumed, "known timestamp provenance retained");
    }

    private static void independent_axis_rotations() {
        // Rotate each native tag basis vector one step around X, then Y, then Z.
        // This checks order/signs without duplicating the adapter's expanded matrix formula.
        double[][] angles = {{90, 0, 0}, {0, 90, 0}, {0, 0, 90}, {30, -20, 40}, {-70, 80, -110}};
        for (double[] angle : angles) {
            HivePoseEstimator.Observation observation = HiveLimelightObservation.from_target_pose(
                    30, pose(DistanceUnit.METER, 0, 0, 2, angle[0], angle[1], angle[2]), 1);
            double[] matrix = observation.rotation_camera_tag();
            for (int column = 0; column < 3; column++) {
                double[] basis = new double[3];
                basis[column] = 1;
                double[] rotated = rotate_stepwise(basis, angle);
                vector(new double[]{rotated[2], -rotated[0], -rotated[1]},
                        new double[]{matrix[column], matrix[3 + column], matrix[6 + column]},
                        "optical rotation column " + column);
            }
        }
    }

    private static void official_inverse_pose_example() {
        // Published paired t6t_cs / t6c_ts values, not a pose generated by our own solver:
        // https://docs.limelightvision.io/docs/docs-limelight/apis/json-results-specification
        double[] targetOptical = {-.09991902572799474, -.1234042720218289, 2.5218203039582496};
        double[] cameraTarget = {.33247368976801916, -.05672695778305914, -2.5042031405987144};
        HivePoseEstimator.Observation observation = HiveLimelightObservation.from_target_pose(
                2, pose(DistanceUnit.METER, targetOptical[0], targetOptical[1], targetOptical[2],
                        4.278368708252767, 5.508508005282244, -4.1112864453027775), 1);
        double[] matrix = observation.rotation_camera_tag();
        double[] translation = observation.translation_camera_tag();
        for (int axis = 0; axis < 3; axis++) {
            double inverseInches = -(matrix[axis] * translation[0]
                    + matrix[3 + axis] * translation[1] + matrix[6 + axis] * translation[2]);
            near(cameraTarget[axis] / .0254, inverseInches,
                    "published camera-in-target inverse component " + axis);
        }
    }

    private static void complete_pose_example() {
        // Hand-calculated worked example in native optical SDK coordinates. Its Euler angles
        // correspond to camera-FLU Ry(-30), not a second copy of the adapter's matrix formula.
        HivePoseEstimator.Observation observation = HiveLimelightObservation.from_target_pose(30,
                pose(DistanceUnit.INCH, -8, -(30-10*Math.sqrt(3)), 70, 180, -60, -90), 100);
        HivePoseEstimator.TagModel tag = new HivePoseEstimator.TagModel(30,
                new double[]{100,100,40}, new double[]{1,0,0},
                new double[]{0,0,20}, new double[]{0,1,0}, false, "synthetic example");
        HivePoseEstimator estimator = new HivePoseEstimator(new HivePoseEstimator.TagModel[]{tag},
                new HivePoseEstimator.CameraMount(new double[]{1,0,0,0,1,0,0,0,1},
                        new double[]{4,2,10}, false));
        HivePoseEstimator.Result result = estimator.estimate(observation, new double[]{0,0,-1});
        check(result != null, "SDK-to-final-pose calculation succeeds");
        near(90,result.x,"complete example X");
        near(164,result.y,"complete example Y");
        near(0,result.z,"complete example floor height");
        near(-Math.PI/2,result.heading,"complete example heading");
    }

    private static void invalid_observations() {
        rejects(() -> HiveLimelightObservation.from_target_pose(30, null, 1), "missing pose");
        rejects(() -> HiveLimelightObservation.from_fiducial(null, 1), "missing fiducial");
        rejects(() -> HiveLimelightObservation.from_target_pose(30,
                pose(DistanceUnit.METER, 0, 0, 0, 0, 0, 0), 1), "SDK missing-3D zero pose");
        rejects(() -> HiveLimelightObservation.from_target_pose(30,
                pose(DistanceUnit.METER, 0, 0, -1, 0, 0, 0), 1), "behind-camera pose");
        rejects(() -> HiveLimelightObservation.from_target_pose(30,
                pose(DistanceUnit.METER, Double.NaN, 0, 1, 0, 0, 0), 1), "NaN translation");
        rejects(() -> HiveLimelightObservation.from_target_pose(30,
                pose(DistanceUnit.METER, 0, 0, 1, 0, Double.NaN, 0), 1), "NaN orientation");
        check(HiveLimelightObservation.from_result(null, 1).isEmpty(), "missing frame has no observations");
    }

    private static Pose3D pose(DistanceUnit unit, double x, double y, double z,
                               double roll, double pitch, double yaw) {
        return new Pose3D(new Position(unit, x, y, z, 0),
                new YawPitchRollAngles(AngleUnit.DEGREES, yaw, pitch, roll, 0));
    }

    private static double[] rotate_stepwise(double[] vector, double[] degrees) {
        double x = vector[0], y = vector[1], z = vector[2];
        double r = Math.toRadians(degrees[0]), p = Math.toRadians(degrees[1]);
        double w = Math.toRadians(degrees[2]);
        double rxY = Math.cos(r) * y - Math.sin(r) * z;
        double rxZ = Math.sin(r) * y + Math.cos(r) * z;
        double ryX = Math.cos(p) * x + Math.sin(p) * rxZ;
        double ryZ = -Math.sin(p) * x + Math.cos(p) * rxZ;
        return new double[]{Math.cos(w) * ryX - Math.sin(w) * rxY,
                Math.sin(w) * ryX + Math.cos(w) * rxY, ryZ};
    }

    private static void vector(double[] expected, double[] actual, String message) {
        check(actual.length == expected.length, message + " dimensions");
        for (int i = 0; i < expected.length; i++) near(expected[i], actual[i], message + " component " + i);
    }

    private static void near(double expected, double actual, String message) {
        check(Double.isFinite(actual) && Math.abs(expected - actual) <= 1e-9, message);
    }

    private static void check(boolean condition, String message) {
        checks++;
        if (!condition) throw new AssertionError(message);
    }

    private static void rejects(Runnable action, String message) {
        boolean rejected = false;
        try { action.run(); } catch (IllegalArgumentException expected) { rejected = true; }
        check(rejected, message);
    }
}
